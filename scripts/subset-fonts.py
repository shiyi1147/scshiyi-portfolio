import sys,json,hashlib,re
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont
text=''.join(chr(i) for i in range(32,127))+'，。！？：；（）《》·—…＋−→←　'
for p in Path('src').rglob('*'):
 if p.suffix in ['.js','.jsx','.css','.json']: text+=p.read_text(encoding='utf-8')
text+=Path('index.html').read_text(encoding='utf-8')
archive_source=Path('src/archiveContent.js').read_text(encoding='utf-8')
projects=json.loads(archive_source[archive_source.index('['):archive_source.rindex('];')+1])
first=next(p for p in projects if p['id']=='archive-shanhai')
basic=''.join(chr(i) for i in range(32,127))+'，。！？：；（）《》·—…＋−→←　'
home_ui=basic+Path('src/ImmersiveWork.jsx').read_text(encoding='utf-8')+Path('src/InternshipAvailability.jsx').read_text(encoding='utf-8')+(first.get('note') or first.get('eyebrow',''))
home_titles=basic+''.join(p.get('name',p['title']) for p in projects if p.get('group')!='interface')
home_titles+=''.join(re.findall(r"name:'([^']+)'",Path('src/watchfaceCollection.js').read_text(encoding='utf-8')))
home_texts={'misans-normal.ttf':home_ui,'zaozigongfang-yihei.otf':home_titles}
families={'misans-normal.ttf':'MiSans Portfolio','zaozigongfang-yihei.otf':'Zaozi Yihei Portfolio'}

def ranges(points):
 values=sorted(points); result=[]
 if not values:return ''
 start=end=values[0]
 for value in values[1:]:
  if value==end+1:end=value
  else:
   result.append(f'U+{start:X}'+(f'-{end:X}' if end!=start else ''));start=end=value
 result.append(f'U+{start:X}'+(f'-{end:X}' if end!=start else ''))
 return ','.join(result)

report=[]
versions={}
faces=[]
for name in ['misans-normal.ttf','pangmen-display.ttf','zaozigongfang-yihei.otf']:
 p=Path('public/assets/fonts')/name; dest=p.with_name(p.stem+'-subset.woff2')
 # Keep the source font timestamp so identical text produces identical assets.
 font=TTFont(p,recalcTimestamp=False); cmap=font.getBestCmap(); required=set(map(ord,text)) & set(cmap)
 options=subset.Options();options.flavor='woff2';options.layout_features=['*']
 worker=subset.Subsetter(options=options);worker.populate(unicodes=sorted(required));worker.subset(font);font.flavor='woff2';font.save(dest)
 assert required <= set(TTFont(dest).getBestCmap())
 version=hashlib.sha256(dest.read_bytes()).hexdigest()[:12]
 versions[dest.name]=version
 chinese={ord(c) for c in text if 0x3400<=ord(c)<=0x9fff or 0x20000<=ord(c)<=0x3134f}
 row={'font':name,'fullWoff2':p.with_suffix('.woff2').stat().st_size,'subset':dest.stat().st_size,'characters':len(required),'version':version,'unsupportedChinese':''.join(chr(c) for c in sorted(chinese-set(cmap)))}
 if name in home_texts:
  critical=set(map(ord,home_texts[name])) & set(cmap)
  assert critical <= required
  home=p.with_name(p.stem+'-home.woff2')
  small=TTFont(p,recalcTimestamp=False)
  home_worker=subset.Subsetter(options=options);home_worker.populate(unicodes=sorted(critical));home_worker.subset(small);small.flavor='woff2';small.save(home)
  assert critical <= set(TTFont(home).getBestCmap())
  home_version=hashlib.sha256(home.read_bytes()).hexdigest()[:12];versions[home.name]=home_version
  for file,hash_value,characters in [(home,home_version,critical),(dest,version,required-critical)]:
   if characters:faces.append(f'@font-face {{font-family:"{families[name]}";src:url("/assets/fonts/{file.name}?v={hash_value}") format("woff2");font-style:normal;font-weight:400;font-display:swap;unicode-range:{ranges(characters)};}}')
  row.update(homeFont=home.name,homeVersion=home_version,homeBytes=home.stat().st_size,homeCharacters=len(critical))
 report.append(row)
Path('src/fontFaces.css').write_text('/* Generated by scripts/subset-fonts.py; home and remaining ranges are disjoint. */\n'+'\n'.join(faces)+'\n',encoding='utf-8')
# Update both @font-face sources and preload links. Old cached subsets must not
# be reused when newly published text introduces additional characters.
for target in ['src/styles.css','src/SpatialIndex.css','index.html']:
 p=Path(target); original=p.read_text(encoding='utf-8'); updated=original
 if target=='index.html':updated=updated.replace('assets/fonts/zaozigongfang-yihei-subset.woff2','assets/fonts/zaozigongfang-yihei-home.woff2')
 for filename,version in versions.items():
  pattern=r'(assets/fonts/'+re.escape(filename)+r')(?:\?v=[0-9a-f]+)?'
  updated=re.sub(pattern,lambda match:match.group(1)+'?v='+version,updated)
 if updated!=original: p.write_text(updated,encoding='utf-8')
Path('output/font-subset-report.json').write_text(json.dumps(report,indent=2),encoding='utf-8');print(json.dumps(report))
